    samples = [
        "设这个矩形的一条边长为狓ｍ，则另一条边长为（１２－狓）ｍ．",
        "犪狓２＋犫狓＋犮＞０或犪狓２＋犫狓＋犮＜０，其中犪，犫，犮均为常数，犪≠０．",
        "设矩形犃犅犆犇（犃犅＞犃犇）的周长为２４ｃｍ",
        "全体非负整数组成的集合称为非负整数集（或自然数集），记作犖；",
    ]
    for s in samples:
        print(restore_fz_italic(s))
