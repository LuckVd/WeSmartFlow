"""
方正书版数学教材"斜体拉丁字母/数字"CJK乱码还原表
=================================================
根源：这批人教版教材PDF由"方正书版"系统排版，公式里的斜体拉丁字母
（用于表示数学变量，如 x, y, a, b, A, B）使用专有字体 E-BX9（白斜体），
其编码表把这些拉丁字符映射到 CJK 统一表意文字区（U+72xx 附近）的冷僻汉字
码位上。这是已知的行业问题（搜"方正书版 白斜 BX字体"能查到多篇讨论），
poppler/pdftotext 和多数通用工具都不认识这层私有映射，直接按 Unicode
码位显示，所以看起来像乱码汉字。数字本身不受影响（pymupdf提取出来就是
正常ASCII 0-9，只有拉丁字母走了这套私有映射）。

验证方法：用 pymupdf 按字体名筛出白斜体（E-BX9/H-SS9等含"BX"关键字的
字体）span，在人教A版《数学必修第一册》全书269页范围内收集每个乱码字符
的真实语境（如"犚"必出现在"实数集犚""狓∈犚"等强语义场景，对应R；
"犈犉犌犎"是矩形/正方形四个顶点连用，必为E/F/G/H），逆向锁定字母。
26个小写字母 + 21个大写字母（A-V）全部有直接语境证据；W/X/Y/Z 因为
样本书里未出现全部21个大写字母，按同一字体区剩余连续码位（排除掉码位
本身是常用汉字的位置）推断，置信度略低于其余字母，标注在下方注释里。

使用：
    from fzsp_font_fix import restore_fz_italic
    clean_text = restore_fz_italic(raw_text)
"""

# 大写字母 A-V：全部21个字符均已用全书真实语境验证。
# W/X/Y/Z：未在该书样本中直接出现，按同一字体区连续码位推断（已排除常用汉字码位），
# 置信度略低，若后续在其他教材验证发现有误，只需在此处修正
UPPER_MAP = {
    'A': '犃', 'B': '犅', 'C': '犆', 'D': '犇', 'E': '犈', 'F': '犉',
    'G': '犌', 'H': '犎', 'I': '犐', 'J': '犑', 'K': '犓', 'L': '犔',
    'M': '犕', 'N': '犖', 'O': '犗', 'P': '犘', 'Q': '犙', 'R': '犚',
    'S': '犛', 'T': '犜', 'U': '犝', 'V': '犞',
    'W': '犠', 'X': '犡', 'Y': '犢', 'Z': '犣',  # 推断，未直接验证
}

# 小写字母 a-z：全部 26 个字符均已用全书真实语境验证（a=犪…z=狕）
LOWER_MAP = {
    'a': '犪', 'b': '犫', 'c': '犮', 'd': '犱', 'e': '犲', 'f': '犳',
    'g': '犵', 'h': '犺', 'i': '犻', 'j': '犼', 'k': '犽', 'l': '犾',
    'm': '犿', 'n': '狀', 'o': '狅', 'p': '狆', 'q': '狇', 'r': '狉',
    's': '狊', 't': '狋', 'u': '狌', 'v': '狏', 'w': '狑', 'x': '狓',
    'y': '狔', 'z': '狕',
}

# 反向映射（乱码字符 -> 正常拉丁字母），实际替换时用这个
_REVERSE_MAP = {v: k for k, v in {**UPPER_MAP, **LOWER_MAP}.items()}

# 全角数字/全角ASCII标点：pdftotext 提取时这些是标准 Unicode 全角字符
# （如"２"是 U+FF12，"＋"是 U+FF0B），不属于本表要处理的私有映射问题，
# 但为了让还原后的文本更适合阅读/检索，一并转换成半角
_FULLWIDTH_ASCII = {chr(0xFF01 + i): chr(0x21 + i) for i in range(94)}


def restore_fz_italic(text: str, fullwidth_to_halfwidth: bool = True) -> str:
    """把方正书版斜体乱码还原成正常拉丁字母，可选顺带把全角ASCII转半角。"""
    out = []
    for ch in text:
        if ch in _REVERSE_MAP:
            out.append(_REVERSE_MAP[ch])
        elif fullwidth_to_halfwidth and ch in _FULLWIDTH_ASCII:
            out.append(_FULLWIDTH_ASCII[ch])
        else:
            out.append(ch)
    return ''.join(out)


